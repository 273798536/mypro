const generateEvidenceChain = (sampleId: string, includeLeak: boolean) => {
  const chain = [
    {
      id: `E-${sampleId}-1`,
      type: 'sample' as const,
      title: '样本原始标注',
      content: '样本表中记录的属性值与商品参数对比',
      originalStatement: mockSamples.find(s => s.id === sampleId)?.originalStatement,
      sampleId,
      severity: 'high' as const,
    },
    {
      id: `E-${sampleId}-2`,
      type: 'rule' as const,
      title: '属性匹配规则',
      content: '根据《商品属性标注规范V3.2》第5.1条进行判定',
      severity: 'medium' as const,
    },
  ];
  
  if (includeLeak) {
    chain.push({
      id: `E-${sampleId}-3`,
      type: 'leak' as const,
      title: '样本引用缺失',
      content: '报告中引用了样本结论但未标注具体样本来源',
      originalStatement: '报告原文："根据历史样本数据，该属性应标注为XXX"',
      sampleId,
      severity: 'high' as const,
    });
  }
  
  return chain;
};


const generatePressurePoints = (
  baseTime: string,
  count: number,
  anomalies: { start: number; end: number; type: string }[] = []
) => {
  const points = [];
  const base = dayjs(baseTime);
  for (let i = 0; i < count; i++) {
    let pressure = 22 + Math.sin(i * 0.3) * 2 + Math.random() * 1;
    for (const anomaly of anomalies) {
      if (i >= anomaly.start && i <= anomaly.end) {
        if (anomaly.type === 'spike') {
          pressure = 33 + Math.random() * 3;
        } else if (anomaly.type === 'drop') {
          pressure = 15 + Math.random() * 2;
        } else if (anomaly.type === 'fluctuation') {
          pressure = 22 + Math.sin(i * 1.5) * 5;
        } else if (anomaly.type === 'over_limit') {
          pressure = 29 + Math.random() * 2;
        }
      }
    }
    points.push({
      timestamp: base.add(i * 10, 'second').format('YYYY-MM-DD HH:mm:ss'),
      pressure: Number(pressure.toFixed(2)),
      temperature: Number((45 + Math.random() * 10).toFixed(1)),
    });
  }
  return points;
};


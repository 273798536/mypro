export const generateMockCards = (
  difficulty: Difficulty = 'medium',
  count: number = 10
): ConversationCard[] => {
  let filtered = rawCardData.filter(card => {
    if (difficulty === 'easy') return card.difficulty === 'easy';
    if (difficulty === 'medium') return card.difficulty !== 'hard';
    return true;
  });

  const shuffled = [...filtered].sort(() => Math.random() - 0.5);
  const selected = shuffled.slice(0, Math.min(count, shuffled.length));

  return selected.map(rawCard => {
    const result = dirtyDataHandler.handleDirtyData(rawCard);
    return result.card;
  });
};

export const getAllMockCards = (): ConversationCard[] => {
  return rawCardData.map(rawCard => {
    const result = dirtyDataHandler.handleDirtyData(rawCard);
    return result.card;
  });
};

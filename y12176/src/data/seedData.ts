const generateAnswerRecords = (questionId: string, count: number, correctRate: number): AnswerRecord[] => {
  const students = ['张三', '李四', '王五', '赵六', '陈七', '刘八', '周九', '吴十', '郑一', '孙二'];
  const records: AnswerRecord[] = [];
  for (let i = 0; i < count; i++) {
    records.push({
      id: `ans-${questionId}-${i}`,
      questionId,
      studentId: `stu-${i % 10}`,
      studentName: students[i % 10],
      isCorrect: Math.random() < correctRate,
      answerTime: now - Math.random() * 30 * 24 * 60 * 60 * 1000,
      score: Math.floor(Math.random() * 10) + 1,
    });
  }
  return records;
};

const generateChangeHistory = (questionId: string): ChangeRecord[] => {
  const changes: ChangeRecord[] = [];
  if (Math.random() > 0.6) {
    const difficulties = ['easy', 'medium', 'hard'];
    const oldDiff = difficulties[Math.floor(Math.random() * 3)];
    const newDiff = difficulties[Math.floor(Math.random() * 3)];
    if (oldDiff !== newDiff) {
      changes.push({
        id: `chg-${questionId}-1`,
        questionId,
        field: 'difficulty',
        oldValue: oldDiff,
        newValue: newDiff,
        operator: '李教研员',
        timestamp: now - Math.random() * 60 * 24 * 60 * 60 * 1000,
        remark: '根据答题数据调整难度',
      });
    }
  }
  return changes;
};


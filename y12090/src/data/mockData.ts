function generateMockSeats(): Seat[] {
  const seats: Seat[] = [];
  const rows = ['A', 'B', 'C', 'D', 'E', 'F', 'G', 'H'];
  const seatsPerRow = 14;
  const rowSpacing = 1.5;
  const seatSpacing = 1.2;
  const stageZ = -12;

  for (let rowIdx = 0; rowIdx < rows.length; rowIdx++) {
    const rowName = rows[rowIdx];
    const z = rowIdx * rowSpacing;
    const y = rowIdx * 0.15;

    for (let seatNum = 1; seatNum <= seatsPerRow; seatNum++) {
      const x = (seatNum - seatsPerRow / 2 - 0.5) * seatSpacing;

      seats.push({
        id: `seat-${rowName}-${seatNum}`,
        row: rowName,
        number: seatNum,
        section: seatNum <= 4 ? '左侧区' : seatNum >= 11 ? '右侧区' : '中央区',
        position: { x, y, z },
        eyeHeight: 1.2,
        targetPoint: {
          x: (Math.random() - 0.5) * 2,
          y: 2 + Math.random() * 1,
          z: stageZ,
        },
      });
    }
  }

  return seats;
}


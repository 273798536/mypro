const createSample = (
  id: string,
  name: string,
  generation: string,
  pathologyNote: string,
  contaminationProb: number,
  contaminationType: 'pollen' | 'cross-sample' | 'other' | undefined,
  hasMutations: boolean,
  hasCultureRecord: boolean,
  qcStatus: 'pass' | 'fail' | 'pending',
  lineageInfo: Partial<LineageNode>
): Sample => {
  const mutations = hasMutations ? mockMutations.map(m => ({
    ...m,
    id: `${m.id}-${id}`,
  })) : [];

  return {
    id,
    name,
    generation,
    pathologyNote,
    qcStatus,
    qcMetrics: {
      gcContent: 45 + Math.random() * 5,
      q30: 88 + Math.random() * 8,
      depth: Math.floor(20 + Math.random() * 30),
      mappingRate: 95 + Math.random() * 4,
      duplicateRate: 5 + Math.random() * 5,
      totalReads: Math.floor(10000000 + Math.random() * 5000000),
    },
    contamination: {
      probability: contaminationProb,
      type: contaminationType,
      evidenceLoci: contaminationProb > 80
        ? ['TraesCS1A01G001200', 'TraesCS2B01G003400', 'TraesCS3D01G005600'].slice(0, Math.floor(Math.random() * 3) + 2)
        : [],
      confidence: (contaminationProb > 85 ? 'high' : contaminationProb > 60 ? 'medium' : 'low') as 'low' | 'medium' | 'high',
      reviewed: false,
    },
    mutations,
    cultureRecord: hasCultureRecord
      ? {
          pollinationDate: new Date('2026-04-15'),
          harvestDate: new Date('2026-05-20'),
          plantingDate: new Date('2026-03-01'),
          growthCondition: '温室栽培，25℃/18℃昼夜，光照16h',
          notes: '常规水肥管理，无病虫害发生',
          lastUpdated: new Date('2026-06-10'),
        }
      : undefined,
    lineageInfo: {
      id: `lineage-${id}`,
      sampleId: id,
      generation: lineageInfo.generation || 0,
      parentId: lineageInfo.parentId,
      motherId: lineageInfo.motherId,
      fatherId: lineageInfo.fatherId,
      childrenIds: lineageInfo.childrenIds || [],
      relationToParent: lineageInfo.relationToParent,
      needsReview: lineageInfo.needsReview || false,
      reviewReason: lineageInfo.reviewReason,
      reviewStatus: lineageInfo.reviewStatus || 'none',
      reviewedBy: lineageInfo.reviewedBy,
      reviewedAt: lineageInfo.reviewedAt,
      requiresCorrection: lineageInfo.requiresCorrection,
      version: 1,
      cultureRecords: lineageInfo.cultureRecords || [],
      mutations: mutations.map(m => m.id),
    },
  };
};


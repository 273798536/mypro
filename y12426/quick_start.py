def main():
    if len(sys.argv) > 1:
        arg = sys.argv[1]
        if arg == "intro":
            show_intro()
        elif arg == "model":
            show_data_model()
        elif arg == "workflow":
            show_workflow()
        elif arg == "trace":
            show_traceability()
        elif arg == "exception":
            show_exception_scenarios()
        elif arg == "views":
            show_views()
        elif arg == "checklist":
            show_checklist()

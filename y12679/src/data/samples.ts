import type { SampleData, PathNode } from '@/types'

const generatePathNodes = (
  startX: number,
  startY: number,
  endX: number,
  endY: number,
  baseVelocity: number,
  baseTemperature: number,
  points: number = 20
): PathNode[] => {
  const nodes: PathNode[] = []
  for (let i = 0; i <= points; i++) {
    const t = i / points
    const wobble = Math.sin(t * Math.PI * 3) * 15
    nodes.push({
      x: startX + (endX - startX) * t + wobble * (i > 0 && i < points ? 1 : 0),
      y: startY + (endY - startY) * t + wobble * 0.3 * (i > 0 && i < points ? 1 : 0),
      velocity: baseVelocity + Math.sin(t * Math.PI * 2) * 0.3,
      temperature: baseTemperature + Math.cos(t * Math.PI) * 1.5,
    })
  }
  return nodes
}


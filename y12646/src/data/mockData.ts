const now = Date.now();

function generateTrajectoryPoints(centerX: number, centerY: number, count: number, accuracy: number): Trajectory['points'] {
  const points: Trajectory['points'] = [];
  const variance = (1 - accuracy) * 30;
  for (let i = 0; i < count; i++) {
    const t = i / count;
    const angle = t * Math.PI * 4;
    const radius = 5 + Math.random() * variance;
    points.push({
      x: centerX + Math.cos(angle) * radius + (Math.random() - 0.5) * variance * 0.5,
      y: centerY + Math.sin(angle) * radius + (Math.random() - 0.5) * variance * 0.5,
      timestamp: now - (count - i) * 200,
      pressure: 40 + Math.random() * 40,
    });
  }
  return points;
}


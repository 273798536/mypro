export const generateHourlyTide = (
  baseDate: string,
  highHeight: number,
  highHour: number,
  lowHeight: number,
  lowHour: number
) => {
  const hourly: { time: string; height: number }[] = [];
  for (let h = 0; h < 24; h++) {
    const t = h;
    let height: number;
    if (t <= lowHour) {
      const ratio = t / lowHour;
      height = highHeight - (highHeight - lowHeight) * (1 - Math.cos(ratio * Math.PI)) / 2;
    } else if (t <= highHour) {
      const ratio = (t - lowHour) / (highHour - lowHour);
      height = lowHeight + (highHeight - lowHeight) * (1 - Math.cos(ratio * Math.PI)) / 2;
    } else {
      const ratio = (t - highHour) / (24 - highHour);
      height = highHeight - (highHeight - lowHeight) * (1 - Math.cos(ratio * Math.PI)) / 2;
    }
    const hourStr = h.toString().padStart(2, '0');
    hourly.push({
      time: `${baseDate} ${hourStr}:00`,
      height: Math.round(height * 100) / 100,
    });
  }
  return hourly;
};


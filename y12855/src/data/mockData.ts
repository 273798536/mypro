function genTrajectory(
  inspectionId: string,
  startLat: number,
  startLng: number,
  endLat: number,
  endLng: number,
  count: number,
  driftFactor = 0,
): TrajectoryPoint[] {
  const points: TrajectoryPoint[] = [];
  const startTime = new Date("2026-06-12T05:30:00Z").getTime();
  for (let i = 0; i < count; i++) {
    const t = i / (count - 1);
    const noise = (Math.sin(i * 0.7) * driftFactor) / 111000;
    const lat = startLat + (endLat - startLat) * t + noise;
    const lng = startLng + (endLng - startLng) * t + noise * 0.7;
    points.push({
      id: `${inspectionId}-tp-${i}`,
      inspectionId,
      lat: Number(lat.toFixed(6)),
      lng: Number(lng.toFixed(6)),
      timestamp: new Date(startTime + i * 5 * 60 * 1000).toISOString(),
      speedKnots: Number((4.5 + Math.sin(i * 0.5) * 1.2 + driftFactor * 0.001).toFixed(1)),
    });
  }
  return points;
}


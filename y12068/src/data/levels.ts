export function getLevelById(id: string): LevelData | undefined {
  return levels.find((l) => l.id === id)
}

export function detectConflicts(level: LevelData): ConflictItem[] {
  const conflicts: ConflictItem[] = []

  for (const track of level.partTracks) {
    for (const note of track.notes) {
      const beat = level.beatLines.find((b) => b.tick === note.tick)
      if (!beat) continue

      if (note.isEntry && beat.isRest) {
        conflicts.push({
          type: 'entry_mismatch',
          partTrackId: track.id,
          partTrackName: track.name,
          beatLineTick: beat.tick,
          beatLineLabel: beat.label,
          partTrackValue: `第${note.tick + 1}拍有声部进入音符`,
          beatLineValue: `第${note.tick + 1}拍标记为休止`,
          description: `${track.name}在休止拍有进入音符，与节拍线冲突`,
        })
      }

      if (!note.isEntry && beat.isRest) {
        conflicts.push({
          type: 'rest_overlap',
          partTrackId: track.id,
          partTrackName: track.name,
          beatLineTick: beat.tick,
          beatLineLabel: beat.label,
          partTrackValue: `第${note.tick + 1}拍有音符`,
          beatLineValue: `第${note.tick + 1}拍标记为休止`,
          description: `${track.name}在休止拍有音符，与节拍线冲突`,
        })
      }
    }
  }

  return conflicts
}

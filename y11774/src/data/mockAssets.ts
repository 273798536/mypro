import type { Asset, TimeWindow } from '@/types';

const generateReturns = (baseReturn: number, volatility: number, count: number): number[] => {
  return Array.from({ length: count }, () => {
    const noise = (Math.random() - 0.5) * volatility;
    return baseReturn + noise;
  });
};

const generateAllReturns = (base: number, vol: number): Record<TimeWindow, number[]> => ({
  '1m': generateReturns(base, vol * 1.5, 22),
  '3m': generateReturns(base, vol * 1.2, 66),
  '6m': generateReturns(base, vol, 132),
  '1y': generateReturns(base, vol * 0.8, 252),
  '3y': generateReturns(base, vol * 0.6, 756),
  '5y': generateReturns(base, vol * 0.5, 1260),
});

